//! The web app on the hub's origin, with the SPA fallback to `index.html`.
//!
//! Where it comes from, in order: the folder in `HUBNESS_WEB_DIST` when that is set
//! explicitly (development); the copy compiled into the binary with the `embed-web`
//! feature (installed hubs); the default folder `apps/web/dist` when it exists.

use axum::Router;
use tower_http::services::{ServeDir, ServeFile};

use crate::{AppState, Config};

/// Attach the web app to `router` as its fallback, if there is one to serve.
pub fn attach(router: Router<AppState>, config: &Config) -> Router<AppState> {
    let dist = &config.web_dist;
    if !config.web_dist_explicit && embedded::available() {
        return router.fallback(embedded::serve);
    }
    if dist.is_dir() {
        return router.fallback_service(ServeDir::new(dist).fallback(ServeFile::new(dist.join("index.html"))));
    }
    router
}

#[cfg(not(feature = "embed-web"))]
mod embedded {
    pub fn available() -> bool {
        false
    }

    pub async fn serve() -> axum::http::StatusCode {
        axum::http::StatusCode::NOT_FOUND
    }
}

#[cfg(feature = "embed-web")]
mod embedded {
    use axum::body::Body;
    use axum::http::{HeaderMap, HeaderValue, Method, StatusCode, Uri, header};
    use axum::response::{IntoResponse, Response};

    /// One file of the built web app.
    pub struct Asset {
        pub path: &'static str,
        pub etag: &'static str,
        pub bytes: &'static [u8],
    }

    // `ASSETS`, sorted by path (generated by build.rs)
    include!(concat!(env!("OUT_DIR"), "/web_assets.rs"));

    pub fn available() -> bool {
        find("index.html").is_some()
    }

    fn find(path: &str) -> Option<&'static Asset> {
        ASSETS.binary_search_by(|a| a.path.cmp(path)).ok().map(|i| &ASSETS[i])
    }

    /// Like `ServeDir` with the `index.html` fallback: the file at the path, the
    /// `index.html` of a folder, or the app's `index.html` for every other path.
    pub async fn serve(method: Method, uri: Uri, headers: HeaderMap) -> Response {
        if method != Method::GET && method != Method::HEAD {
            return (StatusCode::METHOD_NOT_ALLOWED, [(header::ALLOW, "GET, HEAD")]).into_response();
        }
        let decoded = percent_encoding::percent_decode_str(uri.path()).decode_utf8_lossy();
        let path = decoded.trim_start_matches('/');
        let asset = if path.is_empty() || path.ends_with('/') { find(&format!("{path}index.html")) } else { find(path) };
        let Some(asset) = asset.or_else(|| find("index.html")) else {
            return StatusCode::NOT_FOUND.into_response();
        };
        let fresh = headers.get(header::IF_NONE_MATCH).and_then(|v| v.to_str().ok()).is_some_and(|v| {
            v.split(',').any(|t| {
                let t = t.trim();
                t == "*" || t.trim_start_matches("W/") == asset.etag
            })
        });
        // Vite puts content-hashed files under assets/: those never change
        let cache = if asset.path.starts_with("assets/") { "public, max-age=31536000, immutable" } else { "no-cache" };
        let mime = mime_guess::from_path(asset.path).first_or_octet_stream();
        let mut res = if fresh {
            StatusCode::NOT_MODIFIED.into_response()
        } else {
            let mut res = Response::new(Body::from(asset.bytes));
            if let Ok(v) = HeaderValue::from_str(mime.as_ref()) {
                res.headers_mut().insert(header::CONTENT_TYPE, v);
            }
            res
        };
        let h = res.headers_mut();
        h.insert(header::ETAG, HeaderValue::from_static(asset.etag));
        h.insert(header::CACHE_CONTROL, HeaderValue::from_static(cache));
        res
    }
}

#[cfg(test)]
mod tests {
    use axum::body::Body;
    use axum::http::{Request, StatusCode};
    use tower::ServiceExt;

    use crate::{AppState, Config};

    fn state(web_dist: &std::path::Path, explicit: bool) -> (tempfile::TempDir, AppState) {
        let tmp = tempfile::tempdir().unwrap();
        let mut config = Config::new(0, "127.0.0.1".into(), &tmp.path().join("data"), &tmp.path().join("hub"), web_dist);
        config.web_dist_explicit = explicit;
        (tmp, AppState::open(config).unwrap())
    }

    async fn get(state: AppState, path: &str) -> (StatusCode, String) {
        let res = crate::app(state).oneshot(Request::get(path).body(Body::empty()).unwrap()).await.unwrap();
        let status = res.status();
        let body = axum::body::to_bytes(res.into_body(), usize::MAX).await.unwrap();
        (status, String::from_utf8_lossy(&body).into_owned())
    }

    #[tokio::test]
    async fn an_explicit_folder_wins_with_the_spa_fallback() {
        let web = tempfile::tempdir().unwrap();
        std::fs::write(web.path().join("index.html"), "<p>from the folder</p>").unwrap();
        std::fs::create_dir(web.path().join("assets")).unwrap();
        std::fs::write(web.path().join("assets/app.js"), "console.log(1)").unwrap();
        let (_tmp, s) = state(web.path(), true);
        assert_eq!(get(s.clone(), "/assets/app.js").await, (StatusCode::OK, "console.log(1)".into()));
        assert_eq!(get(s.clone(), "/projects/abc").await, (StatusCode::OK, "<p>from the folder</p>".into()));
        assert_eq!(get(s, "/api/nope").await.0, StatusCode::NOT_FOUND);
    }

    #[cfg(feature = "embed-web")]
    #[tokio::test]
    async fn the_embedded_app_without_an_explicit_folder() {
        let web = tempfile::tempdir().unwrap();
        let (_tmp, s) = state(&web.path().join("missing"), false);
        let (status, index) = get(s.clone(), "/").await;
        assert_eq!(status, StatusCode::OK);
        assert!(index.contains("<html"));
        assert_eq!(get(s.clone(), "/projects/abc").await, (StatusCode::OK, index));
        assert_eq!(get(s, "/api/nope").await.0, StatusCode::NOT_FOUND);
    }

    #[tokio::test]
    async fn a_missing_explicit_folder_serves_no_web_app() {
        let web = tempfile::tempdir().unwrap();
        let (_tmp, s) = state(&web.path().join("missing"), true);
        assert_eq!(get(s, "/").await.0, StatusCode::NOT_FOUND);
    }
}
