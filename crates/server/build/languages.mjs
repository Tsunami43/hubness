// Generates crates/server/src/languages_data.rs from the `linguist-languages` npm package
// (the GitHub Linguist data the TypeScript server uses in apps/server/src/languages.ts).
//
//   node crates/server/build/languages.mjs     (after pnpm install)
//
// The lookup tables are resolved here exactly like languages.ts builds them at startup
// (extension rank, PREFER overrides, file names), so the Rust side only does lookups.
// Keep PREFER in sync with apps/server/src/languages.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const require = createRequire(join(repo, 'apps/server/package.json'));
const entry = require.resolve('linguist-languages');
const pkg = JSON.parse(readFileSync(join(dirname(entry), 'package.json'), 'utf8'));
const linguist = await import(pathToFileURL(entry).href);

const LANGS = Object.values(linguist).filter((l) => l && typeof l === 'object' && 'type' in l);
const PREFER = {
  '.ts': 'TypeScript',
  '.h': 'C',
  '.m': 'Objective-C',
  '.pl': 'Perl',
  '.pm': 'Perl',
  '.r': 'R',
  '.cs': 'C#',
  '.fs': 'F#',
  '.rs': 'Rust',
  '.sql': 'SQL',
  '.md': 'Markdown',
  '.v': 'Verilog',
  '.inc': 'PHP',
  '.cls': 'Apex',
  '.l': 'Lex',
  '.mod': 'Modula-2',
  '.toc': 'TeX',
  '.html': 'HTML',
  '.json': 'JSON',
  '.yml': 'YAML',
  '.yaml': 'YAML',
};

const byExt = new Map();
const byName = new Map();
const rank = (l) => (l.type === 'programming' ? 0 : l.type === 'markup' ? 1 : 2);
for (const l of LANGS) {
  for (const e of l.extensions ?? []) {
    const key = e.toLowerCase();
    const cur = byExt.get(key);
    if (!cur || rank(l) < rank(cur)) byExt.set(key, l);
  }
  for (const f of l.filenames ?? []) byName.set(f, l);
}
for (const [ext, name] of Object.entries(PREFER)) {
  const l = LANGS.find((x) => x.name === name);
  if (l) byExt.set(ext, l);
}

// only programming and markup languages are counted; the others still stop the lookup
const counted = (l) => l.type === 'programming' || l.type === 'markup';
const langs = [];
const index = new Map();
const idx = (l) => {
  if (!counted(l)) return 'SKIPPED';
  if (!index.has(l)) {
    index.set(l, langs.length);
    langs.push(l);
  }
  return String(index.get(l));
};
// JSON string escapes are valid Rust string escapes for this data (no \u{...} needed)
const str = (s) => JSON.stringify(s);
const byKey = (a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);
// Rust compares &str bytewise: sort by UTF-8 bytes, not UTF-16 units
const utf8 = (a, b) => Buffer.compare(Buffer.from(a[0]), Buffer.from(b[0])) || byKey(a, b);
const table = (m) => [...m].map(([k, l]) => [k, idx(l)]).sort(utf8);
const ext = table(byExt);
const names = table(byName);

const out = `// @generated by crates/server/build/languages.mjs from linguist-languages ${pkg.version}. Do not edit.
// Regenerate: pnpm install && node crates/server/build/languages.mjs

/// Marks a language that is known but not counted (data, prose): the lookup stops there.
pub const SKIPPED: u16 = u16::MAX;

/// Counted languages: (name, color).
pub static LANGUAGES: &[(&str, Option<&str>)] = &[
${langs.map((l) => `    (${str(l.name)}, ${l.color ? `Some(${str(l.color)})` : 'None'}),`).join('\n')}
];

/// Lower-case extension (with the dot) → index in LANGUAGES, sorted for binary search.
pub static EXTENSIONS: &[(&str, u16)] = &[
${ext.map(([k, v]) => `    (${str(k)}, ${v}),`).join('\n')}
];

/// Exact file name → index in LANGUAGES, sorted for binary search.
pub static FILENAMES: &[(&str, u16)] = &[
${names.map(([k, v]) => `    (${str(k)}, ${v}),`).join('\n')}
];
`;
writeFileSync(join(repo, 'crates/server/src/languages_data.rs'), out);
console.log(`languages_data.rs: ${langs.length} languages, ${ext.length} extensions, ${names.length} file names`);
